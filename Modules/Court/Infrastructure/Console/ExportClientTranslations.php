<?php

declare(strict_types=1);

namespace Modules\Court\Infrastructure\Console;

use Illuminate\Console\Command;

/**
 * Writes court-ms's translation files (lang/{en,am}/*.php) as the React
 * screens' dictionary, so a React page says exactly what the Blade page it
 * replaces said: `__('court::cases.status.pending')` is `t('cm.cases.status.pending')`.
 * The output is committed (like resources/js/ziggy.js); `--check` fails when
 * it is out of date, which the test suite runs.
 */
final class ExportClientTranslations extends Command
{
    protected $signature = 'court:client-lang {--check : Fail instead of writing when the files are out of date}';

    protected $description = 'Export lang/{en,am}/*.php for the React screens (resources/js/court/i18n/lang)';

    /** Server-only text: validation and password-broker messages reach the client already translated. */
    private const SKIP = ['validation', 'passwords'];

    public function handle(): int
    {
        $stale = [];
        foreach (['en', 'am'] as $locale) {
            $target = resource_path("js/court/i18n/lang/{$locale}.ts");
            $contents = $this->render($locale);
            if ($this->option('check')) {
                if (! is_file($target) || file_get_contents($target) !== $contents) {
                    $stale[] = $target;
                }

                continue;
            }
            if (! is_dir(dirname($target))) {
                mkdir(dirname($target), 0775, true);
            }
            file_put_contents($target, $contents);
            $this->info("Wrote {$target}");
        }

        if ($stale !== []) {
            $this->error('Out of date (run php artisan court:client-lang): '.implode(', ', $stale));

            return self::FAILURE;
        }

        return self::SUCCESS;
    }

    private function render(string $locale): string
    {
        $tree = $this->tree($locale);

        // A key the language lacks falls back to the fallback locale's text, as
        // Laravel's `__()` does on the server, so a React page never shows a raw key.
        $fallback = 'en';
        if ($locale !== $fallback) {
            $tree = array_replace_recursive($this->tree($fallback), $tree);
        }

        $json = json_encode($tree, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);

        return "// Generated by `php artisan court:client-lang` from lang/{$locale}/*.php. Do not edit.\n"
            ."const lang: Record<string, unknown> = {$json};\n\n"
            ."export default lang;\n";
    }

    /** The court module's own lang folder (Modules/Court/resources/lang). */
    private static function langPath(string $path): string
    {
        return dirname(__DIR__, 2).'/resources/lang/'.$path;
    }

    /** @return array<string, mixed> */
    private function tree(string $locale): array
    {
        $tree = [];
        $files = glob(self::langPath("{$locale}/*.php")) ?: [];
        sort($files);
        foreach ($files as $file) {
            $group = basename($file, '.php');
            if (in_array($group, self::SKIP, true)) {
                continue;
            }
            $lines = require $file;
            if (is_array($lines)) {
                $tree[$group] = $lines;
            }
        }

        // The plain strings of lang/{locale}.json (`__('Case Types')`) under `json`, by their English text.
        $jsonFile = self::langPath("{$locale}.json");
        $tree['json'] = is_file($jsonFile) ? (array) json_decode((string) file_get_contents($jsonFile), true, 512, JSON_THROW_ON_ERROR) : [];

        return $tree;
    }
}

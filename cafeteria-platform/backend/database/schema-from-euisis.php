<?php

declare(strict_types=1);

/*
 * Prints a Laravel migration for the cafeteria tables as they are in a live
 * EUISIS PostgreSQL database (columns, defaults, indexes and the foreign keys
 * between the listed tables), so the standalone cafeteria platform keeps the
 * EUISIS schema without replaying EUISIS's own migration history.
 *
 *   php database/schema-from-euisis.php "pgsql:host=127.0.0.1;port=5432;dbname=aaemployeedb" user password > database/migrations/2026_11_01_100000_create_cafeteria_tables.php
 *
 * Foreign keys to tables outside the list (users, employees, organizations…)
 * are kept only when the referenced table exists in the cafeteria platform
 * (KEPT_REFERENCES); the column stays either way.
 */
[$dsn, $user, $password] = [$argv[1] ?? '', $argv[2] ?? '', $argv[3] ?? ''];
$tables = array_slice($argv, 4);
if ($dsn === '' || $tables === []) {
    fwrite(STDERR, "usage: php schema-from-euisis.php <dsn> <user> <password> <table...>\n");
    exit(1);
}

const KEPT_REFERENCES = ['users', 'employees', 'employee_assignments', 'organizations', 'organization_units', 'positions', 'id_cards'];

$pdo = new PDO($dsn, $user, $password, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$q = fn (string $sql, array $params = []): array => (function () use ($pdo, $sql, $params) {
    $s = $pdo->prepare($sql);
    $s->execute($params);

    return $s->fetchAll(PDO::FETCH_ASSOC);
})();

$out = [];
$out[] = '<?php';
$out[] = '';
$out[] = 'declare(strict_types=1);';
$out[] = '';
$out[] = 'use Illuminate\Database\Migrations\Migration;';
$out[] = 'use Illuminate\Database\Schema\Blueprint;';
$out[] = 'use Illuminate\Support\Facades\Schema;';
$out[] = '';
$out[] = '/*';
$out[] = ' * The EUISIS cafeteria tables, as EUISIS has them (generated by database/schema-from-euisis.php';
$out[] = ' * from a live EUISIS database on '.date('Y-m-d').'). Do not edit by hand: regenerate.';
$out[] = ' */';
$out[] = 'return new class extends Migration';
$out[] = '{';
$out[] = '    public function up(): void';
$out[] = '    {';

$fkLines = [];
foreach ($tables as $table) {
    $columns = $q("select column_name, data_type, udt_name, character_maximum_length, numeric_precision, numeric_scale, is_nullable, column_default, datetime_precision
        from information_schema.columns where table_schema = 'public' and table_name = ? order by ordinal_position", [$table]);
    if ($columns === []) {
        fwrite(STDERR, "no such table: $table\n");
        exit(1);
    }
    $pk = array_column($q('select a.attname from pg_index i join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any(i.indkey)
        where i.indrelid = ?::regclass and i.indisprimary', ['public.'.$table]), 'attname');
    $out[] = "        Schema::create('$table', function (Blueprint \$table): void {";
    foreach ($columns as $c) {
        $name = $c['column_name'];
        $default = $c['column_default'];
        $isSerial = $default !== null && str_starts_with($default, 'nextval(');
        $line = match (true) {
            $isSerial && $c['data_type'] === 'bigint' => "\$table->bigIncrements('$name')",
            $isSerial => "\$table->increments('$name')",
            $c['data_type'] === 'uuid' => "\$table->uuid('$name')",
            $c['data_type'] === 'character varying' => "\$table->string('$name'".($c['character_maximum_length'] && (int) $c['character_maximum_length'] !== 255 ? ', '.$c['character_maximum_length'] : '').')',
            $c['data_type'] === 'character' => "\$table->char('$name', ".$c['character_maximum_length'].')',
            $c['data_type'] === 'text' => "\$table->text('$name')",
            $c['data_type'] === 'bigint' => "\$table->bigInteger('$name')",
            $c['data_type'] === 'integer' => "\$table->integer('$name')",
            $c['data_type'] === 'smallint' => "\$table->smallInteger('$name')",
            $c['data_type'] === 'boolean' => "\$table->boolean('$name')",
            $c['data_type'] === 'numeric' => "\$table->decimal('$name', ".$c['numeric_precision'].', '.$c['numeric_scale'].')',
            $c['data_type'] === 'double precision' => "\$table->double('$name')",
            $c['data_type'] === 'real' => "\$table->float('$name')",
            $c['data_type'] === 'date' => "\$table->date('$name')",
            $c['data_type'] === 'time without time zone' => "\$table->time('$name')",
            str_starts_with($c['data_type'], 'timestamp') => "\$table->timestamp('$name')",
            in_array($c['data_type'], ['json', 'jsonb'], true) => "\$table->json('$name')",
            default => throw new RuntimeException("$table.$name: unmapped type {$c['data_type']}"),
        };
        if ($c['is_nullable'] === 'YES') {
            $line .= '->nullable()';
        }
        if ($default !== null && ! $isSerial) {
            $line .= '->default('.phpDefault($default, $c['data_type']).')';
        }
        if (count($pk) === 1 && $pk[0] === $name && ! $isSerial) {
            $line .= '->primary()';
        }
        $out[] = "            $line;";
    }
    if (count($pk) > 1) {
        $out[] = "            \$table->primary(['".implode("', '", $pk)."']);";
    }
    // Indexes (unique and plain), without the primary key and without partial indexes (noted).
    $indexes = $q('select i.relname as name, ix.indisunique as is_unique, pg_get_indexdef(ix.indexrelid) as def, ix.indpred is not null as partial
        from pg_index ix join pg_class i on i.oid = ix.indexrelid where ix.indrelid = ?::regclass and not ix.indisprimary order by i.relname', ['public.'.$table]);
    foreach ($indexes as $ix) {
        if (! preg_match('/\((.*)\)/', $ix['def'], $m)) {
            continue;
        }
        $cols = array_map(fn (string $s): string => trim($s, ' "'), explode(',', $m[1]));
        if (array_filter($cols, fn (string $s): bool => str_contains($s, '(') || str_contains($s, ' '))) {
            $out[] = '            // expression index kept out: '.$ix['def'];

            continue;
        }
        if ($ix['partial']) {
            $out[] = '            // partial index kept out: '.$ix['def'];

            continue;
        }
        $shortName = strlen($ix['name']) > 60 ? null : $ix['name'];
        $out[] = '            $table->'.($ix['is_unique'] ? 'unique' : 'index')."(['".implode("', '", $cols)."']".($shortName ? ", '$shortName'" : '').');';
    }
    $out[] = '        });';
    $out[] = '';

    $fks = $q("select con.conname, con.confrelid::regclass::text as ref_table,
            (select string_agg(a.attname, ',' order by u.ord) from unnest(con.conkey) with ordinality u(attnum, ord) join pg_attribute a on a.attrelid = con.conrelid and a.attnum = u.attnum) as cols,
            (select string_agg(a.attname, ',' order by u.ord) from unnest(con.confkey) with ordinality u(attnum, ord) join pg_attribute a on a.attrelid = con.confrelid and a.attnum = u.attnum) as ref_cols,
            con.confdeltype, con.confupdtype
        from pg_constraint con where con.conrelid = ?::regclass and con.contype = 'f' order by con.conname", ['public.'.$table]);
    foreach ($fks as $fk) {
        $ref = preg_replace('/^public\./', '', $fk['ref_table']);
        if (! in_array($ref, $tables, true) && ! in_array($ref, KEPT_REFERENCES, true)) {
            $fkLines[] = "        // $table.{$fk['cols']} referenced $ref in EUISIS; that table is not in the cafeteria platform.";

            continue;
        }
        $onDelete = match ($fk['confdeltype']) {
            'c' => '->cascadeOnDelete()', 'n' => '->nullOnDelete()', 'r' => '->restrictOnDelete()', default => ''
        };
        $onUpdate = match ($fk['confupdtype']) {
            'c' => '->cascadeOnUpdate()', default => ''
        };
        $fkLines[] = "        Schema::table('$table', fn (Blueprint \$table) => \$table->foreign(['".str_replace(',', "', '", $fk['cols'])."'], '{$fk['conname']}')->references(['".str_replace(',', "', '", $fk['ref_cols'])."'])->on('$ref')$onDelete$onUpdate);";
    }
}
$out[] = '        // Foreign keys after every table exists.';
foreach ($fkLines as $line) {
    $out[] = $line;
}
$out[] = '    }';
$out[] = '';
$out[] = '    public function down(): void';
$out[] = '    {';
$out[] = '        Schema::disableForeignKeyConstraints();';
foreach (array_reverse($tables) as $table) {
    $out[] = "        Schema::dropIfExists('$table');";
}
$out[] = '        Schema::enableForeignKeyConstraints();';
$out[] = '    }';
$out[] = '};';
echo implode("\n", $out), "\n";

function phpDefault(string $default, string $type): string
{
    $default = preg_replace('/::[a-z ]+(\[\])?$/i', '', $default);
    if (preg_match("/^'(.*)'$/s", $default, $m)) {
        $value = str_replace("''", "'", $m[1]);

        return var_export($value, true);
    }
    if (in_array(strtolower($default), ['true', 'false'], true)) {
        return strtolower($default);
    }
    if (is_numeric($default)) {
        return $default;
    }
    if (in_array(strtolower($default), ['now()', 'current_timestamp'], true)) {
        return 'DB::raw(\'CURRENT_TIMESTAMP\')';
    }
    if (strtolower($default) === 'gen_random_uuid()') {
        return 'DB::raw(\'gen_random_uuid()\')';
    }
    throw new RuntimeException("unmapped default: $default ($type)");
}

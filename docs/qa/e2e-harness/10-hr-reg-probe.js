'use strict';
const { BASE, newBrowser, login, shot } = require('./lib');
const H = require('./10-hr-helpers');
(async () => {
    const state = H.loadState();
    const { browser, page } = await newBrowser();
    const posts = []; H.captureResponses(page, posts);
    const dialogs = [];
    page.on('dialog', async (d) => { dialogs.push(d.type() + ': ' + d.message()); await d.accept(); });
    await login(page, 'qa.sysadmin1@demo.local', 'password');
    await page.goto(BASE + '/employees/create', { waitUntil: 'networkidle' });
    await page.locator('#organization_id').selectOption(state.org1.id);
    await page.waitForLoadState('networkidle'); await page.waitForTimeout(800);
    await page.locator('#organization_unit_id').selectOption(state.unit1.id);
    await page.waitForTimeout(300);
    await page.locator('#position_id').selectOption(state.pos1.id);
    await page.waitForTimeout(300);
    await page.locator('#first_name').fill('QA-Emp');
    await page.locator('#last_name').fill('Probe-' + state.run);
    await page.locator('#gender').selectOption({ index: 1 });
    await page.locator('input[type="date"]').first().fill('1990-05-15');
    await page.locator('#phone').fill('+251911000001');
    await page.locator('#employment_type').selectOption('permanent');
    const mark = H.logMark();
    const t0 = Date.now();
    await page.click('button[type="submit"]');
    await page.waitForTimeout(6000);
    await page.waitForLoadState('networkidle');
    console.log('url', page.url(), 'ms', Date.now() - t0);
    console.log('dialogs', dialogs);
    console.log('posts', JSON.stringify(posts.filter((p) => /\/employees/.test(p.url)), null, 1));
    console.log('errors', await H.fieldErrors(page));
    console.log('msgs', await H.visibleMessages(page));
    const body = await page.locator('body').innerText();
    console.log('body', body.replace(/\s+/g, ' ').slice(0, 400));
    console.log('log', H.logErrorsSince(mark).map((l) => l.slice(0, 400)));
    console.log('row', H.sql(`select id, employee_number, full_name from employees where last_name='Probe-${state.run}'`));
    console.log('locks', H.sql('select * from cache_locks'));
    await shot(page, 'hr-reg-probe');
    await browser.close();
})().catch((e) => { console.error('FATAL', e); process.exit(1); });

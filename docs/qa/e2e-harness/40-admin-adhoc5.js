'use strict';
const path = require('path');
const { BASE, Recorder, newBrowser, login, visit, shot } = require('./lib');
const { FIX, sql, body } = require('./40-admin-lib');
(async () => {
    const R = new Recorder('40-admin-adhoc5');
    const { browser, page } = await newBrowser();
    R.attach(page);
    const me = sql(`select id from users where email='qa.sysadmin5@demo.local'`)[0][0];
    const orig = sql(`select coalesce(gender,''), coalesce(profile_photo_path,''), coalesce(phone_number,'') from users where id=${me}`)[0];
    await login(page, 'qa.sysadmin5@demo.local', 'password');
    await R.step('wrong current password: all responses for 4s', async () => {
        await visit(page, '/profile');
        await page.locator('[role="tab"], button').filter({ hasText: /security/i }).first().click();
        await page.waitForTimeout(300);
        await page.fill('#current_password', 'definitely-wrong');
        await page.fill('#password', 'Marigold-Comet-4482!');
        await page.fill('#password_confirmation', 'Marigold-Comet-4482!');
        const got = [];
        const h = async (r) => { if (!r.url().startsWith(BASE)) return; const e = { m: r.request().method(), url: r.url().replace(BASE, ''), status: r.status(), ct: (r.headers()['content-type'] || '').slice(0, 20), inertia: !!r.request().headers()['x-inertia'] }; try { if (/json/.test(e.ct)) { const j = await r.json(); e.errors = j.props?.errors; e.component = j.component; } } catch {} got.push(e); };
        page.on('response', h);
        await page.evaluate(() => { const b = [...document.querySelectorAll('button')].find((x) => /update password/i.test(x.textContent)); b.click(); });
        await page.waitForTimeout(4000);
        page.off('response', h);
        await shot(page, '40-adhoc5-wrongpw');
        const errText = await page.locator('[id$="-error"], p[class*="text-red"], [role="alert"], [aria-invalid="true"]').allInnerTexts();
        const tabNow = await page.locator('[role="tab"][aria-selected="true"]').allInnerTexts();
        return `responses=${JSON.stringify(got)} errText=${JSON.stringify(errText)} activeTab=${JSON.stringify(tabNow)} url=${page.url().replace(BASE, '')}`;
    }, page);
    await R.step('account form save (gender+photo)', async () => {
        await visit(page, '/profile');
        await page.locator('[role="tab"], button').filter({ hasText: /account/i }).first().click();
        await page.waitForTimeout(300);
        const sel = page.locator('select').filter({ has: page.locator('option[value="female"]') }).first();
        await sel.selectOption('female');
        await page.locator('input[type="file"]').first().setInputFiles(path.join(FIX, 'small.png'));
        const forms = await page.locator('form').count();
        const btns = await page.locator('form button[type=submit]').allInnerTexts();
        const got = [];
        const h = async (r) => { if (!r.url().startsWith(BASE)) return; const e = { m: r.request().method(), url: r.url().replace(BASE, ''), status: r.status() }; try { if (/json/.test(r.headers()['content-type'] || '')) { const j = await r.json(); e.errors = j.props?.errors; e.flash = j.props?.flash?.message; } } catch {} got.push(e); };
        page.on('response', h);
        await page.evaluate(() => { const b = [...document.querySelectorAll('form button[type=submit]')].find((x) => /save/i.test(x.textContent)); (b || document.querySelector('form button[type=submit]')).click(); });
        await page.waitForTimeout(4000);
        page.off('response', h);
        const row = sql(`select coalesce(gender,''), coalesce(profile_photo_path,''), coalesce(phone_number,'') from users where id=${me}`)[0];
        const audit = sql(`select event_type, left(new_values::text,160), coalesce(request_ip,'NULL') from audit_logs where actor_user_id=${me} and event_type in ('profile_updated','profile_photo_updated') order by created_at desc limit 2`);
        await shot(page, '40-adhoc5-profile-updated');
        sql(`update users set gender=${orig[0] ? `'${orig[0]}'` : 'NULL'}, profile_photo_path=${orig[1] ? `'${orig[1]}'` : 'NULL'} where id=${me}`);
        return `forms=${forms} submitButtons=${JSON.stringify(btns)} responses=${JSON.stringify(got).slice(0, 500)} db gender=${row[0]} photo=${row[1]} audit=${audit.map((a) => a.join(' | ')).join(' ;; ')}`;
    }, page);
    await browser.close(); R.save();
})().catch((e) => { console.error('FATAL', e); process.exit(1); });

-- PostgreSQL: create a NEW production Super Admin in an already migrated,
-- role-initialized EUISIS database. Run against the intended production DB.
-- Existing users and role permissions are never updated by this script.
-- Direct SQL bypasses application audit logging and model hooks.
--
-- Replace the three values below before running. Use a NEW email address.
-- Generate the password hash on the production application server:
--   php artisan tinker
--   $password = \Laravel\Prompts\password('New admin password');
--   echo \Illuminate\Support\Facades\Hash::make($password), PHP_EOL;
--   unset($password);
-- Copy ONLY the resulting hash into admin_password_hash below.
-- Never put a plaintext password, MD5, or SHA hash in the password column.
-- Do not commit a copy containing real credentials.

BEGIN;

DO $bootstrap$
DECLARE
    admin_name text := 'REPLACE_WITH_NAME';
    admin_email text := 'REPLACE_WITH_EMAIL';
    admin_password_hash text := 'REPLACE_WITH_APPLICATION_PASSWORD_HASH';
    super_admin_role_id bigint;
    new_user_id bigint;
BEGIN
    IF admin_name = 'REPLACE_WITH_NAME'
       OR admin_email = 'REPLACE_WITH_EMAIL'
       OR admin_password_hash = 'REPLACE_WITH_APPLICATION_PASSWORD_HASH' THEN
        RAISE EXCEPTION 'Replace the name, email, and password hash first.';
    END IF;

    IF admin_password_hash NOT LIKE '$argon2id$%'
       AND admin_password_hash NOT LIKE '$argon2i$%'
       AND admin_password_hash NOT LIKE '$2y$%'
       AND admin_password_hash NOT LIKE '$2b$%' THEN
        RAISE EXCEPTION 'Use a password hash generated by the production application.';
    END IF;

    SELECT id INTO STRICT super_admin_role_id
    FROM roles
    WHERE name = 'Super Admin' AND guard_name = 'web';
    -- If the role is missing, this aborts without creating a user.
    -- Initialize the application's production roles before retrying.

    IF EXISTS (SELECT 1 FROM users WHERE lower(email) = lower(admin_email)) THEN
        RAISE EXCEPTION 'Email already exists; this script only creates new accounts.';
    END IF;

    INSERT INTO users (
        name, email, password, status, is_demo, must_change_password,
        created_at, updated_at
    ) VALUES (
        admin_name, admin_email, admin_password_hash, 'active', false, true,
        CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
    ) RETURNING id INTO new_user_id;

    INSERT INTO model_has_roles (role_id, model_type, model_id)
    VALUES (super_admin_role_id, E'App\\Models\\User', new_user_id);

    RAISE NOTICE 'Created Super Admin user ID % with email %', new_user_id, admin_email;
END
$bootstrap$;

COMMIT;


def body(text, lead=None, keep=False):
    """A justified paragraph; `lead` is a bold run-in heading."""
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    par.paragraph_format.keep_with_next = keep
    if lead:
        add_run(par, lead + " ", bold=True, color=NAVY_RGB)
    add_run(par, text)
    return par


def note(text, lead="ለአሠልጣኞች ማሳሰቢያ፦"):
    """A shaded, justified note box (single-cell table)."""
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    cell = table.rows[0].cells[0]
    cell.width = Cm(CONTENT_W)
    shade(cell, NOTE_FILL)
    cell_margins(cell, 110, 110, 160, 160)
    par = cell.paragraphs[0]
    par.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    par.paragraph_format.space_after = Pt(0)
    add_run(par, lead + " ", bold=True, color=ORANGE_RGB, size=11)
    add_run(par, text, size=11)
    tblpr = table._element.tblPr
    borders = OxmlElement("w:tblBorders")
    left = OxmlElement("w:left")
    left.set(qn("w:val"), "single")
    left.set(qn("w:sz"), "24")
    left.set(qn("w:space"), "0")
    left.set(qn("w:color"), ORANGE)
    borders.append(left)
    tblpr.append(borders)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def make_table(headers, rows, widths, *, justify_cols=(), center_cols=(), section_rows=True, font_size=10.5):
    """
    A designed table: navy header that repeats on each page, banded rows,
    fixed column widths. A row given as a 1-tuple is a section band across
    the whole table. Cells listed in `justify_cols` are justified.
    """
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    table_borders(table)

    head = table.rows[0]
    repeat_header(head)
    no_split(head)
    for i, text in enumerate(headers):
        cell = head.cells[i]
        cell.width = Cm(widths[i])
        shade(cell, NAVY)
        cell_margins(cell, 90, 90)
        cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        par = cell.paragraphs[0]
        par.alignment = WD_ALIGN_PARAGRAPH.CENTER
        par.paragraph_format.space_after = Pt(0)
        add_run(par, text, bold=True, size=font_size, color=RGBColor(0xFF, 0xFF, 0xFF), font=HEAD_FONT)

    band = False
    for row in rows:
        tr = table.add_row()
        if len(row) == 1:  # section band
            merged = tr.cells[0].merge(tr.cells[-1])
            shade(merged, SECTION_FILL)
            cell_margins(merged, 80, 80)
            par = merged.paragraphs[0]
            par.paragraph_format.space_after = Pt(0)
            par.paragraph_format.keep_with_next = True
            add_run(par, row[0], bold=True, size=font_size + 0.5, color=NAVY_RGB, font=HEAD_FONT)
            band = False
            continue
        no_split(tr)
        for i, text in enumerate(row):
            cell = tr.cells[i]
            cell.width = Cm(widths[i])
            cell_margins(cell)
            if band:
                shade(cell, BAND)
            par = cell.paragraphs[0]
            par.paragraph_format.space_after = Pt(0)
            par.paragraph_format.line_spacing = 1.1
            if i in justify_cols:
                par.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            elif i in center_cols:
                par.alignment = WD_ALIGN_PARAGRAPH.CENTER
            else:
                par.alignment = WD_ALIGN_PARAGRAPH.LEFT
            bold = i == 0 and i in center_cols
            add_run(par, text, size=font_size, bold=bold, color=NAVY_RGB if bold else None,
                    font=HEAD_FONT if bold else BODY_FONT)
        band = not band
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return table



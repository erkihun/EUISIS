import { FormEvent, useMemo } from 'react';
import { Head, useForm } from '@inertiajs/react';
import AuthenticatedLayout from '@/Layouts/AuthenticatedLayout';
import PageHeader from '@/Components/PageHeader';
import { useLocale } from '@/hooks/useLocale';
import { Alert, Button, Card, FormField, Input, Select, cx } from '@euisis/ui';

interface ApplicationOption {
    value: string;
    label: string;
    status: string;
    event_types: string[];
}

interface Props {
    subscription: { id: string; name: string; callback_url: string; event_types: string[]; external_application_id: string } | null;
    applications: ApplicationOption[];
}

/** Create or edit a webhook subscription. The signing secret is generated by the server and shown once afterwards. */
export default function IntegrationsForm({ subscription, applications }: Props) {
    const { t } = useLocale();
    const editing = subscription !== null;
    const form = useForm({
        external_application_id: subscription?.external_application_id ?? '',
        name: subscription?.name ?? '',
        callback_url: subscription?.callback_url ?? 'https://',
        event_types: subscription?.event_types ?? ([] as string[]),
    });

    const application = applications.find((option) => option.value === form.data.external_application_id);
    const allowed = useMemo(() => application?.event_types ?? [], [application]);

    function toggle(type: string) {
        form.setData('event_types', form.data.event_types.includes(type)
            ? form.data.event_types.filter((value) => value !== type)
            : [...form.data.event_types, type]);
    }

    function submit(event: FormEvent<HTMLFormElement>) {
        event.preventDefault();
        if (editing) {
            form.patch(route('integrations.subscriptions.update', subscription.id));
        } else {
            form.post(route('integrations.subscriptions.store'));
        }
    }

    const title = editing ? t('integrations.editSubscription') : t('integrations.newSubscription');

    return (
        <AuthenticatedLayout contentWidth="form" header={<PageHeader title={title} description={t('integrations.subscriptionsHint')}
            backHref={editing ? route('integrations.subscriptions.show', subscription.id) : route('integrations.index')} />}>
            <Head title={title} />

            <form onSubmit={submit}>
                <Card className="space-y-5">
                    <FormField label={t('integrations.application')} required error={form.errors.external_application_id}>
                        {({ id, describedBy, invalid }) => (
                            <Select id={id} aria-describedby={describedBy} aria-invalid={invalid} value={form.data.external_application_id} disabled={editing}
                                onChange={(event) => form.setData({ ...form.data, external_application_id: event.target.value, event_types: [] })}>
                                <option value="">—</option>
                                {applications.map((option) => <option key={option.value} value={option.value}>{option.label}</option>)}
                            </Select>
                        )}
                    </FormField>

                    <FormField label={t('integrations.name')} required error={form.errors.name}>
                        {({ id, describedBy, invalid }) => (
                            <Input id={id} aria-describedby={describedBy} aria-invalid={invalid} maxLength={120} required value={form.data.name}
                                onChange={(event) => form.setData('name', event.target.value)} />
                        )}
                    </FormField>

                    <FormField label={t('integrations.callbackUrl')} required description={t('integrations.callbackUrlHint')} error={form.errors.callback_url}>
                        {({ id, describedBy, invalid }) => (
                            <Input id={id} aria-describedby={describedBy} aria-invalid={invalid} type="url" maxLength={2048} required className="font-mono"
                                value={form.data.callback_url} onChange={(event) => form.setData('callback_url', event.target.value)} />
                        )}
                    </FormField>

                    <fieldset>
                        <legend className="text-sm font-medium text-(--app-foreground)">{t('integrations.eventTypes')}</legend>
                        <p className="mt-0.5 text-xs text-(--app-muted-foreground)">{t('integrations.eventTypesHint')}</p>
                        {application && allowed.length === 0 && <Alert tone="warning" className="mt-2">{t('integrations.noEventTypesForApplication')}</Alert>}
                        <div className="mt-2 grid gap-2 sm:grid-cols-2">
                            {allowed.map((type) => {
                                const checked = form.data.event_types.includes(type);
                                return (
                                    <label key={type} className={cx('flex cursor-pointer items-center gap-2 rounded-control border px-3 py-2 text-sm',
                                        checked ? 'border-primary bg-primary-50 dark:bg-primary-950' : 'border-(--app-border) hover:bg-(--app-surface-muted)')}>
                                        <input type="checkbox" className="rounded-sm border-(--app-border-strong) text-primary focus:ring-primary" checked={checked} onChange={() => toggle(type)} />
                                        <code className="font-mono text-xs">{type}</code>
                                    </label>
                                );
                            })}
                        </div>
                        {form.errors.event_types && <p className="mt-1 text-xs text-red-600">{form.errors.event_types}</p>}
                    </fieldset>

                    <div className="flex justify-end">
                        <Button type="submit" variant="primary" loading={form.processing}>{t('integrations.save')}</Button>
                    </div>
                </Card>
            </form>
        </AuthenticatedLayout>
    );
}

#!/usr/bin/env bash
#
# Builds the `production` branch from a source commit (default: main).
#
# The production branch carries only what the application needs to install,
# build and run on a server. Each run adds ONE commit whose tree is the source
# tree minus the development-only paths below, on top of the previous
# production commit. It never merges, so it never conflicts, and the working
# tree and current branch are left untouched.
#
# Usage:  scripts/release/build-production-branch.sh [source-ref]
# Then:   git push origin production
#
set -euo pipefail

SOURCE_REF="${1:-main}"
TARGET_BRANCH="production"

# Development-only paths. Anything the running application reads must NOT be
# listed here (docs/api-management-guide.md is served by API Management).
EXCLUDE=(
    tests
    phpunit.xml.dist
    phpunit.pgsql.xml.dist
    .github
    .claude
    .agents
    skills-lock.json
    .editorconfig
    docs
    ':!docs/api-management-guide.md'
    TRANSFER_MODULE_GUIDE.md
    external-apps
    employeeId_db
    sec-routes.json
    sec-audit.json
    # Agent and editor tooling, local scratch output and load-test scripts.
    .codex
    .mcp.json
    .playwright-mcp
    .serena
    .superpowers
    loadtest
    cognee_stderr.txt
    omniroute_stderr.txt
    # Demo data and synthetic load-test generators: they create fake
    # organizations, employees and accounts and never belong on a production
    # server. Reference seeders (permissions, roles, settings, code rules,
    # organization and unit types, holidays, catalogs) and seeders/data stay:
    # migrations and the running application read them. Model factories stay
    # too: models name them (HasFactory), and nothing in production calls them.
    database/seeders/Demo
    database/seeders/DemoDataSeeder.php
    database/seeders/DatabaseSeeder.php
    database/seeders/UserSeeder.php
    database/seeders/AssessmentSampleFormSeeder.php
    database/seeders/Concerns/DemoPasswords.php
    config/demo.php
    app/Support/Demo
    app/Console/Commands/Demo
    app/Console/Commands/Scale
    app/Console/Commands/Transport/SeedTransportLoadTest.php
)

# Shipped code that still names an excluded class would fail at run time.
LEFT_OUT_REFERENCES='Seeders\\Demo\\|DemoPasswords|DemoDataSeeder|DatabaseSeeder|UserSeeder|AssessmentSampleFormSeeder|Commands\\Scale\\|Support\\Demo\\|SeedTransportLoadTest'

cd "$(git rev-parse --show-toplevel)"
source_sha="$(git rev-parse --verify "${SOURCE_REF}^{commit}")"
parent="$(git rev-parse -q --verify "refs/heads/${TARGET_BRANCH}" || true)"

index="$(mktemp)"
trap 'rm -f "$index"' EXIT
export GIT_INDEX_FILE="$index"
git read-tree "$source_sha"
git rm --cached -r -q --ignore-unmatch -- "${EXCLUDE[@]}"
tree="$(git write-tree)"
unset GIT_INDEX_FILE

if dangling="$(git grep -l -E "$LEFT_OUT_REFERENCES" "$tree" -- app bootstrap config database routes)"; then
    echo "Refusing to build: shipped files refer to code left out of ${TARGET_BRANCH}:" >&2
    echo "$dangling" >&2
    exit 1
fi

if [[ -n "$parent" && "$(git rev-parse "${parent}^{tree}")" == "$tree" ]]; then
    echo "${TARGET_BRANCH} already matches ${SOURCE_REF} (${source_sha:0:7}); nothing to do."
    exit 0
fi

message="Production build of ${SOURCE_REF} ${source_sha:0:7}

Source: ${source_sha}
Generated by scripts/release/build-production-branch.sh; do not edit this
branch by hand. Development-only paths are left out (tests, docs, CI and
tooling files, the separate cafeteria app, demo data and load-test generators)."

commit="$(git commit-tree "$tree" ${parent:+-p "$parent"} -m "$message")"
git update-ref "refs/heads/${TARGET_BRANCH}" "$commit" ${parent:+"$parent"}

echo "${TARGET_BRANCH} -> ${commit:0:7} (from ${SOURCE_REF} ${source_sha:0:7}); $(git ls-tree -r --name-only "$commit" | wc -l) files."
echo "Publish with: git push origin ${TARGET_BRANCH}"

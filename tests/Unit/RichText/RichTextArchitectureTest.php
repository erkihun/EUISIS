<?php

declare(strict_types=1);

use Symfony\Component\Finder\Finder;

/*
 * The rich-text infrastructure is built once (docs/rich-text-editor.md):
 * one editor component, one viewer, one adapter that knows the library, one
 * sanitizer. These checks keep it that way as modules adopt it.
 */

function richTextSources(string $directory, string $pattern = '*.tsx'): Finder
{
    return (new Finder)->files()->in(dirname(__DIR__, 3).'/'.$directory)->name([$pattern, '*.ts'])->notPath('i18n');
}

function richTextRelative(SplFileInfo $file): string
{
    return str_replace(dirname(__DIR__, 3).'/', '', $file->getPathname());
}

it('lets only the adapter import the editor library', function (): void {
    $importers = [];
    foreach (richTextSources('resources/js') as $file) {
        if (preg_match("~from\\s+'(tinymce|@tinymce/[^']+)|import\\s+'tinymce|import\\('tinymce~", $file->getContents()) === 1) {
            $importers[] = richTextRelative($file);
        }
    }

    sort($importers);
    // tinymceGlobal.ts holds only the core, so it runs before the adapter's plugins.
    expect($importers)->toBe(['resources/js/richtext/TinyMceAdapter.tsx', 'resources/js/richtext/tinymceGlobal.ts']);
});

it('lets only RichTextEditor load the adapter', function (): void {
    $importers = [];
    foreach (richTextSources('resources/js') as $file) {
        if (str_contains($file->getContents(), 'richtext/TinyMceAdapter')) {
            $importers[] = richTextRelative($file);
        }
    }

    expect($importers)->toBe(['resources/js/Components/forms/RichTextEditor.tsx']);
});

it('renders raw HTML only through the viewer and the reviewed exceptions', function (): void {
    $sites = [];
    foreach (richTextSources('resources/js') as $file) {
        if (str_contains($file->getContents(), 'dangerouslySetInnerHTML')) {
            $sites[] = richTextRelative($file);
        }
    }
    sort($sites);

    expect($sites)->toBe([
        // Formatted text: DOMPurify against policy.json, after the server sanitizer.
        'resources/js/Components/forms/RichTextViewer.tsx',
        // Public-site Markdown, sanitized by SafeContentRenderer on the server.
        'resources/js/Components/public/PublicPage.tsx',
        // Laravel paginator labels (&laquo; / &raquo;) generated by the framework.
        'resources/js/Pages/Discipline/Index.tsx',
    ]);
});

it('keeps the editor off public and citizen-facing pages', function (): void {
    $offenders = [];
    foreach (['resources/js/Pages/Public', 'resources/js/Pages/ServiceFeedback', 'resources/js/Components/public', 'resources/js/Components/ServiceFeedback'] as $directory) {
        if (! is_dir(dirname(__DIR__, 3).'/'.$directory)) {
            continue;
        }
        foreach (richTextSources($directory) as $file) {
            if (str_contains($file->getContents(), 'RichTextEditor')) {
                $offenders[] = richTextRelative($file);
            }
        }
    }

    expect($offenders)->toBe([]);
});

it('echoes stored HTML in Blade only through @richtext or the reviewed exceptions', function (): void {
    $sites = [];
    foreach ((new Finder)->files()->in(dirname(__DIR__, 3).'/resources/views')->name('*.blade.php') as $file) {
        foreach (explode("\n", $file->getContents()) as $line) {
            if (str_contains($line, '{!!')) {
                $sites[] = richTextRelative($file).': '.trim($line);
            }
        }
    }

    expect($sites)->toBe([
        'resources/views/grievances/letter.blade.php: <div class="body">{!! nl2br(e($letter->body)) !!}</div>',
        'resources/views/pdf/partials/typography.blade.php: {!! app(\App\Support\Typography\DocumentFonts::class)->css($variant ?? \'report\') !!}',
    ]);
});

it('keeps the editor presets inside the server allowlist', function (): void {
    $policy = json_decode((string) file_get_contents(dirname(__DIR__, 3).'/resources/js/richtext/policy.json'), true, flags: JSON_THROW_ON_ERROR);
    $presets = (string) file_get_contents(dirname(__DIR__, 3).'/resources/js/richtext/policy.ts');
    preg_match_all('~const (?:BASIC|STANDARD|DOCUMENT)_TAGS = \\[(.*?)\\]~', $presets, $lists);
    preg_match_all("~'([a-z0-9]+)'~", implode(',', $lists[1]), $tags);

    expect(array_diff(array_unique($tags[1]), $policy['tags']))->toBe([])
        ->and($policy['tags'])->not->toContain('script', 'iframe', 'img', 'style', 'object', 'embed', 'span', 'div', 'font')
        ->and($policy['schemes'])->toBe(['http', 'https', 'mailto', 'tel'])
        ->and($policy['styles'])->toBe(['text-align']);
});
